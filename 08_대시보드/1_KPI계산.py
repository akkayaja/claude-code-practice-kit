# 미션 1: 대시보드에 넣을 핵심 숫자(KPI) 4개를 계산해서 화면에 보여 준다
#   - 총매출   = 매출액을 모두 더한 값
#   - 총주문수 = 주문수를 모두 더한 값
#   - 객단가   = 총매출 ÷ 총주문수  (주문 1건에 평균 얼마 썼나)
#   - 전환율   = 총주문수 ÷ 총방문자수 × 100  (방문자 100명 중 몇 명이 샀나)
# 추가 도구 없이 맥에 기본으로 있는 파이썬(python3)만으로 돌아간다.

import csv

CSV_파일 = "data/일별_채널별_매출_2025.csv"

# 1) CSV 읽기 (utf-8-sig: 파일 맨 앞의 보이지 않는 표시(BOM)를 무시하고 읽는 방식)
with open(CSV_파일, encoding="utf-8-sig") as f:
    rows = list(csv.DictReader(f))

# 2) 전체 합계와 채널별 합계 구하기
전체 = {"주문수": 0, "매출액": 0, "방문자수": 0}
채널별 = {}  # 예: {"쿠팡": {"주문수": .., "매출액": .., "방문자수": ..}, ...}

for row in rows:
    채널 = row["채널"]
    if 채널 not in 채널별:
        채널별[채널] = {"주문수": 0, "매출액": 0, "방문자수": 0}
    for 항목 in ["주문수", "매출액", "방문자수"]:
        값 = int(row[항목])
        전체[항목] += 값
        채널별[채널][항목] += 값


def kpi_계산(합계):
    """합계 숫자로 KPI 4개를 계산한다."""
    return {
        "총매출": 합계["매출액"],
        "총주문수": 합계["주문수"],
        "객단가": 합계["매출액"] / 합계["주문수"],
        "전환율": 합계["주문수"] / 합계["방문자수"] * 100,
    }


# 3) 화면에 보여 주기
print(f"읽은 데이터: {len(rows)}줄 (기간 {rows[0]['날짜']} ~ {rows[-1]['날짜']}, 채널 {len(채널별)}개)")
print()

k = kpi_계산(전체)
print("===== 2025년 전체 KPI =====")
print(f"총매출   : {k['총매출']:>15,}원")
print(f"총주문수 : {k['총주문수']:>15,}건")
print(f"객단가   : {k['객단가']:>15,.0f}원")
print(f"전환율   : {k['전환율']:>15.2f}%")
print(f"(참고) 총방문자수: {전체['방문자수']:,}명")
print()

print("===== 채널별 KPI =====")
print(f"{'채널':<8}{'총매출(원)':>16}{'주문수':>10}{'객단가(원)':>12}{'전환율':>9}")
for 채널, 합계 in 채널별.items():
    k = kpi_계산(합계)
    print(f"{채널:<8}{k['총매출']:>16,}{k['총주문수']:>10,}{k['객단가']:>12,.0f}{k['전환율']:>8.2f}%")
