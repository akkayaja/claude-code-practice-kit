# 02번 실습: 팀별 실적 엑셀 5개를 모아 주간보고서를 자동으로 만드는 스크립트
# 실행 방법(터미널):  .venv/bin/python report.py          → 11월 전체
#                    .venv/bin/python report.py 3주차    → 3주차만

import sys                 # 실행할 때 뒤에 붙인 말(예: 3주차)을 받아 오는 도구
from datetime import date  # 오늘 날짜를 알아내는 도구
from pathlib import Path   # 파일·폴더 위치를 다루는 도구
import pandas as pd        # 엑셀 같은 표 데이터를 다루는 도구

# ── 0) 폴더 위치 정하기 ──────────────────────────────
기준폴더 = Path(__file__).parent      # 이 report.py가 들어 있는 폴더
데이터폴더 = 기준폴더 / "data"         # 그 안의 data 폴더

# ── 미션 2-① 팀 파일 5개 읽어서 하나로 합치기 ─────────
표목록 = []                                        # 빈 바구니
for 파일 in sorted(데이터폴더.glob("*_실적.xlsx")):  # '_실적.xlsx'로 끝나는 파일을 하나씩
    표 = pd.read_excel(파일)                        # 엑셀 한 장 읽기
    팀이름 = 파일.stem.split("_")[0]                # '영업1팀_11월_실적' → '영업1팀'
    표.insert(0, "팀", 팀이름)                      # 맨 앞에 '팀' 칸 붙이기 (모둠 스티커)
    표목록.append(표)                               # 바구니에 넣기
    print(f"  읽음: {파일.name} ({len(표)}줄)")

전체 = pd.concat(표목록, ignore_index=True)         # 바구니 속 5장을 한 묶음으로 철하기
print(f"→ 파일 {len(표목록)}개를 합쳐서 업무 {len(전체)}줄이 됐어요\n")

# ── 도전 미션: 주차 고르기 ─────────────────────────────
#    sys.argv = 실행 명령을 띄어쓰기로 자른 목록
#    'python report.py 3주차' → ['report.py', '3주차']  → [1]번이 '3주차'
if len(sys.argv) > 1:                              # 뒤에 뭔가 붙여서 실행했다면
    주차 = sys.argv[1]                              # 예: '3주차'
    전체 = 전체[전체["주차"].str.endswith(주차)]      # '11월 3주차'처럼 끝이 맞는 줄만 남기기
    if len(전체) == 0:                              # 한 줄도 없으면 잘못 입력한 것
        print(f"'{주차}'에 해당하는 업무가 없어요. 예: 1주차, 2주차, 3주차, 4주차")
        sys.exit(1)                                 # 여기서 멈추기
    기간 = f"2026년 11월 {주차}"
    파일이름 = f"주간보고_11월_{주차}.md"
    print(f"→ {주차}만 골랐어요: {len(전체)}줄\n")
else:                                               # 아무것도 안 붙였으면 11월 전체
    기간 = "2026년 11월"
    파일이름 = "주간보고_11월.md"

# ── 미션 2-② 전체 건수 · 완료 건수 · 달성률 계산 ──────
전체건수 = len(전체)                               # 줄 수 = 업무 수
완료건수 = (전체["진행상태"] == "완료").sum()       # '완료'인 줄만 세기
달성률 = round(완료건수 / 전체건수 * 100, 1)        # 완료 ÷ 전체 × 100, 소수 첫째 자리까지

print(f"전체 {전체건수}건 / 완료 {완료건수}건 / 달성률 {달성률}%\n")

# ── 미션 3 팀별 실적 표 만들기 ─────────────────────────
#    groupby("팀") = 같은 모둠 스티커끼리 줄 세우기
#    그다음 모둠마다 전체·완료·진행중·지연 개수를 세요
팀별 = 전체.groupby("팀").agg(
    전체=("업무명", "size"),                                  # 모둠의 줄 수
    완료=("진행상태", lambda 칸: (칸 == "완료").sum()),        # '완료' 개수
    진행중=("진행상태", lambda 칸: (칸 == "진행중").sum()),    # '진행중' 개수
    지연=("진행상태", lambda 칸: (칸 == "지연").sum()),        # '지연' 개수
)
팀별["달성률(%)"] = (팀별["완료"] / 팀별["전체"] * 100).round(1)
팀별 = 팀별.sort_values("달성률(%)", ascending=False)          # 달성률 높은 팀이 위로

print("[팀별 실적]")
print(팀별)
print()

# ── 도전 미션: 지연이 많은 팀 찾기 ──────────────────────
#    팀마다 '지연 ÷ 전체 × 100'(지연 비율)을 구해서
#    기준(40%) 이상이면 '경고등'을 켜요. 기준은 숫자만 바꾸면 조절돼요.
지연기준 = 40
팀별["지연비율(%)"] = (팀별["지연"] / 팀별["전체"] * 100).round(1)
경고팀 = 팀별[팀별["지연비율(%)"] >= 지연기준]           # 기준을 넘은 팀만 골라내기

if len(경고팀) > 0:
    경고글 = ", ".join(f"{팀이름}(지연 {int(행['지연'])}건, {행['지연비율(%)']}%)"
                       for 팀이름, 행 in 경고팀.iterrows())
    print(f"⚠️ 지연 주의 팀 (지연 비율 {지연기준}% 이상): {경고글}\n")
else:
    print(f"지연 비율 {지연기준}% 이상인 팀은 없어요 👍\n")

# ── 미션 4 이슈 목록 만들기 (이슈사항이 적힌 줄만) ──────
#    빈 칸은 pandas가 NaN(값 없음)으로 읽어요.
#    fillna("")  : 값 없음 → 빈 글자 ""로 바꾸기
#    str.strip() : 앞뒤 공백 지우기 (스페이스만 들어 있는 칸도 빈 칸으로 취급)
이슈칸 = 전체["이슈사항"].fillna("").astype(str).str.strip()
이슈들 = 전체[이슈칸 != ""]                       # 빈 글자가 아닌 줄만 골라내기 (체)

이슈줄들 = []
for 줄 in 이슈들.itertuples():                   # 골라낸 줄을 하나씩 꺼내서
    이슈줄들.append(f"- [{줄.팀}] {줄.주차} · {줄.업무명} ({줄.진행상태}) — {줄.이슈사항}")
이슈목록 = "\n".join(이슈줄들)                     # 한 줄씩 엔터로 이어 붙이기

print(f"[주요 이슈] {len(이슈들)}건 (이슈 칸이 빈 {len(전체) - len(이슈들)}줄은 뺐어요)")
print(이슈목록)
print()

# ── 미션 5 양식의 {{ }} 빈칸 채워서 저장하기 ──────────
# ① 팀별 표를 마크다운 표 모양( | 칸 | 칸 | )의 글자로 바꾸기
표줄들 = ["| 팀 | 전체 | 완료 | 진행중 | 지연 | 달성률 |",
          "|---|---:|---:|---:|---:|---:|"]           # 머리줄 + 구분줄
for 팀이름, 행 in 팀별.iterrows():
    # 한 줄을 꺼내면 숫자가 12.0처럼 소수로 바뀔 수 있어서 int()로 정수로 되돌려요
    팀칸 = 팀이름
    지연칸 = str(int(행['지연']))
    if 팀이름 in 경고팀.index:                  # 경고등이 켜진 팀이면
        팀칸 = f"**⚠️ {팀이름}**"               # ** ** = 마크다운에서 '굵게'
        지연칸 = f"**{지연칸}**"
    표줄들.append(f"| {팀칸} | {int(행['전체'])} | {int(행['완료'])} | {int(행['진행중'])} | {지연칸} | {행['달성률(%)']}% |")
if len(경고팀) > 0:                             # 표 아래에 경고 한 줄 덧붙이기
    표줄들.append("")
    표줄들.append(f"> ⚠️ **지연 주의** (지연 비율 {지연기준}% 이상): {경고글}")
팀별표 = "\n".join(표줄들)

# ② 빈칸 이름 → 넣을 답 (빈칸 채우기 시험의 답안지)
답안지 = {
    "기간": 기간,
    "작성일": date.today().isoformat(),     # 예: 2026-11-15
    "전체건수": 전체건수,
    "완료건수": 완료건수,
    "달성률": 달성률,
    "팀별표": 팀별표,
    "이슈목록": 이슈목록,
}

# ③ 양식 읽기 → {{이름}}을 답으로 바꾸기
양식파일 = 기준폴더 / "template" / "주간보고_양식.md"
보고서 = 양식파일.read_text(encoding="utf-8")
for 이름, 답 in 답안지.items():
    보고서 = 보고서.replace("{{" + 이름 + "}}", str(답))

# ④ 안 채운 빈칸이 남았으면 멈추고 알려 주기 (실수 방지 안전장치)
assert "{{" not in 보고서, "아직 안 채워진 {{ }} 칸이 있어요!"

# ⑤ 결과 폴더에 저장하기
결과폴더 = 기준폴더 / "결과"
결과폴더.mkdir(exist_ok=True)                 # 결과 폴더가 없으면 만들기
결과파일 = 결과폴더 / 파일이름
결과파일.write_text(보고서, encoding="utf-8")
print(f"저장 완료 → {결과파일.relative_to(기준폴더)}")

# ── 도전 미션: Word(.docx)로도 저장하기 ──────────────────
#    python-docx = 파이썬으로 Word 문서를 만드는 공구
#    빈 Word 문서를 하나 펴고, 제목 → 문단 → 표 → 목록 순서로 한 줄씩 써 넣어요
from docx import Document
from docx.shared import RGBColor

문서 = Document()                                       # 빈 Word 문서 펴기
문서.add_heading(f"{기간} 주간 업무 보고", level=0)       # 큰 제목
문서.add_paragraph(f"작성일: {date.today().isoformat()}")

문서.add_heading("1. 전체 요약", level=1)                 # 소제목
문서.add_paragraph(f"전체 업무 {전체건수}건 중 완료 {완료건수}건 (달성률 {달성률}%)",
                   style="List Bullet")                 # 글머리 기호(•) 문단

문서.add_heading("2. 팀별 실적", level=1)
머리칸 = ["팀", "전체", "완료", "진행중", "지연", "달성률"]
표 = 문서.add_table(rows=1, cols=len(머리칸))             # 머리줄 1줄짜리 표 만들기
표.style = "Table Grid"                                 # 칸마다 테두리 선 긋기
for 칸, 글자 in zip(표.rows[0].cells, 머리칸):
    칸.text = 글자
    칸.paragraphs[0].runs[0].bold = True                # 머리줄은 굵게

for 팀이름, 행 in 팀별.iterrows():                        # 팀마다 한 줄씩 추가
    경고 = 팀이름 in 경고팀.index
    값들 = [f"⚠️ {팀이름}" if 경고 else 팀이름,
           int(행["전체"]), int(행["완료"]), int(행["진행중"]), int(행["지연"]),
           f"{행['달성률(%)']}%"]
    새줄 = 표.add_row().cells
    for 칸, 값 in zip(새줄, 값들):
        글 = 칸.paragraphs[0].add_run(str(값))
        if 경고:                                        # 경고 팀이면 빨간 굵은 글씨
            글.bold = True
            글.font.color.rgb = RGBColor(0xC0, 0x00, 0x00)

if len(경고팀) > 0:
    경고문단 = 문서.add_paragraph()
    글 = 경고문단.add_run(f"⚠️ 지연 주의 (지연 비율 {지연기준}% 이상): {경고글}")
    글.bold = True
    글.font.color.rgb = RGBColor(0xC0, 0x00, 0x00)

문서.add_heading("3. 주요 이슈", level=1)
for 줄 in 이슈들.itertuples():
    문서.add_paragraph(f"[{줄.팀}] {줄.주차} · {줄.업무명} ({줄.진행상태}) — {줄.이슈사항}",
                       style="List Bullet")

문서.add_heading("4. 다음 주 계획", level=1)
문서.add_paragraph("(담당자가 직접 작성)", style="List Bullet")

워드파일 = 결과파일.with_suffix(".docx")                 # 이름은 같고 끝만 .md → .docx
문서.save(워드파일)
print(f"저장 완료 → {워드파일.relative_to(기준폴더)}")
