# 미션 5: 테스트 질문 9개로 챗봇 채점하기
#  - 챗봇(답하기)에게 9문항을 묻고, 정답표의 '기대답변'과 비교해 채점해요
#  - 채점은 '채점 선생님' 역할의 Claude가 해요 (문장이 달라도 핵심이 맞으면 정답)
#  - 결과는 결과/채점결과.csv 에 저장해요 (엑셀로 열어 볼 수 있어요)

import csv

from 공통 import 답하기, 여기, 클로드에게_묻기, 테스트질문_읽기

# 채점 기준 (사용자가 A안을 골랐어요: 채점 선생님에게도 근거 조각을 보여 주기)
채점_지시문 = """너는 사내 규정 챗봇의 답을 채점하는 선생님이야.
[기대답변]과 [챗봇답변]을 비교하고, 덧붙인 말은 [챗봇이 받은 근거 조각]과 대조해서 채점해.
- 문장 표현이 달라도 핵심(숫자, 가능/불가능, 기한)이 기대답변과 같으면 정답.
- 핵심 숫자가 틀리거나 빠졌으면 오답.
- 기대답변에 없는 말을 덧붙였더라도, 그 내용이 근거 조각에 실제로 적혀 있으면 감점하지 마 (친절한 추가 안내).
- 근거 조각에도 없는 내용을 지어냈을 때만 오답.
- 기대답변이 '문서에 없는 내용'이라면, 챗봇이 '문서에 없다/모른다'고 답해야만 정답.
첫째 줄에는 '정답' 또는 '오답' 한 단어만, 둘째 줄에는 이유를 한 문장으로 써."""

결과줄 = []
정답수 = 0

for 번호, 행 in enumerate(테스트질문_읽기(), start=1):
    답, 찾은것 = 답하기(행["질문"])                         # 챗봇에게 묻기
    근거 = "\n".join(f"- {c['내용']}" for c in 찾은것) or "- (없음)"
    채점 = 클로드에게_묻기(                                 # 채점 선생님에게 맡기기 (근거 조각도 함께)
        f"[질문]\n{행['질문']}\n\n[기대답변]\n{행['기대답변']}\n\n"
        f"[챗봇이 받은 근거 조각]\n{근거}\n\n[챗봇답변]\n{답}",
        채점_지시문,
    )
    줄들 = 채점.splitlines()
    판정 = "정답" if 줄들 and 줄들[0].strip().startswith("정답") else "오답"
    이유 = 줄들[1].strip() if len(줄들) > 1 else ""
    정답수 += 판정 == "정답"

    표시 = "✅" if 판정 == "정답" else "❌"
    print(f"\n{표시} Q{번호}. {행['질문']}")
    print(f"   🤖 챗봇: {답}")
    print(f"   🎯 기대: {행['기대답변']}")
    print(f"   📝 채점 이유: {이유}")

    결과줄.append({
        "번호": 번호, "질문": 행["질문"], "챗봇답변": 답, "기대답변": 행["기대답변"],
        "판정": 판정, "채점이유": 이유,
        "검색1등문서": 찾은것[0]["문서"] if 찾은것 else "(없음)", "근거문서(정답표)": 행["근거문서"],
    })

# 결과를 CSV로 저장 (utf-8-sig = 엑셀에서 한글이 안 깨지는 방식)
(여기 / "결과").mkdir(exist_ok=True)
with open(여기 / "결과" / "채점결과.csv", "w", encoding="utf-8-sig", newline="") as f:
    쓰기 = csv.DictWriter(f, fieldnames=list(결과줄[0].keys()))
    쓰기.writeheader()
    쓰기.writerows(결과줄)

주차비 = 결과줄[-1]["판정"]
print(f"\n📊 점수: 9문항 중 {정답수}개 정답 (목표 8개 이상 → {'통과 🎉' if 정답수 >= 8 else '미달'})")
print(f"🅿️ 주차비 질문(문서에 없음): {주차비}")
print("💾 결과/채점결과.csv 에 저장했어요.")
