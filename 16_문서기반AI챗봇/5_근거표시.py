# 도전 미션 1: 답변마다 근거 문서 이름 표시하기
#  - 테스트 질문 9개에 답하면서, 답 아래에 '📄 근거: 문서이름'을 붙여요
#  - 근거 문서는 '검색에 걸린 조각'이 아니라 'Claude가 실제로 답에 쓴 조각'의 문서예요
#  - 정답표의 근거문서와 같은지도 확인해요

from 공통 import 답하기_근거포함, 테스트질문_읽기

맞음 = 0
for 번호, 행 in enumerate(테스트질문_읽기(), start=1):
    답, 근거문서, 찾은것 = 답하기_근거포함(행["질문"])
    표시근거 = ", ".join(근거문서) if 근거문서 else "(없음)"
    일치 = 표시근거 == 행["근거문서"]
    맞음 += 일치
    print(f"\n❓ Q{번호}. {행['질문']}")
    print(f"   🤖 {답}")
    print(f"   📄 근거: {표시근거}   {'✅' if 일치 else '❌'} (정답표: {행['근거문서']})")

print(f"\n📊 근거 문서 표시: 9문항 중 {맞음}개가 정답표와 같아요")
