# 미션 3: 질문하면 관련 있는 조각(포스트잇)을 찾아서 보여 주기 — AI는 아직 안 써요
#  - 테스트 질문 9개를 하나씩 넣어 보고, 점수가 높은 조각 3개를 보여 줘요
#  - 1등 조각이 정답표의 '근거문서'와 같은 문서인지 채점해요

from 공통 import 검색, 테스트질문_읽기

맞음 = 0
문서있는_질문 = 0

for 번호, 행 in enumerate(테스트질문_읽기(), start=1):
    질문 = 행["질문"]
    찾은것 = 검색(질문, 개수=3)
    print(f"\n❓ Q{번호}. {질문}")
    for 순위, 조각 in enumerate(찾은것, start=1):
        print(f"   {순위}등 (점수 {조각['점수']}) [{조각['문서']}] {조각['내용']}")
        print(f"        ↳ 겹친 말: {', '.join(조각['겹친말']) or '없음'}")

    if 행["근거문서"] == "(없음)":
        print("   📭 정답표: 관련 문서 없음 (점수가 낮게 나오는지 보세요)")
        continue
    문서있는_질문 += 1
    if 찾은것 and 찾은것[0]["문서"] == 행["근거문서"]:
        맞음 += 1
        print(f"   ✅ 1등 조각이 정답 문서({행['근거문서']})예요")
    else:
        print(f"   ❌ 1등 조각이 정답 문서({행['근거문서']})가 아니에요")

print(f"\n📊 검색 채점: 문서가 있는 질문 {문서있는_질문}개 중 {맞음}개에서 1등 조각이 정답 문서")
