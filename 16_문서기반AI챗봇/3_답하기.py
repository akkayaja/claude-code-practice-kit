# 미션 4: 찾은 조각을 근거로 Claude가 답하게 하기 (RAG 완성!)
#  - 그냥 실행하면 예시 질문 3개(연차·배우자 출산·주차비)에 답해요
#  - 뒤에 질문을 붙이면 그 질문에 답해요
#    예) ../03_메일분류/.venv/bin/python 3_답하기.py "반차 시간이 어떻게 돼요?"

import sys

from 공통 import 답하기

if len(sys.argv) > 1:                       # 명령 뒤에 질문을 붙였으면 그 질문 하나만
    질문들 = [" ".join(sys.argv[1:])]
else:                                       # 아니면 예시 질문 3개
    질문들 = [
        "입사 8개월 차인데 연차가 며칠이에요?",
        "배우자 출산하면 휴가 며칠?",
        "주차비 지원 되나요?",
    ]

for 질문 in 질문들:
    답, 찾은것 = 답하기(질문)
    print(f"\n❓ {질문}")
    print(f"   📎 Claude에게 건넨 조각 {len(찾은것)}개:")
    for c in 찾은것:
        print(f"      - {c['내용']}")
    print(f"   🤖 답: {답}")
