# 미션 2-②: 작가 에이전트에게 개요를 건네고 '초안'을 맡기기 (수동 2단계)
#  1_개요.py 가 남긴 결과/주제1/1_개요.md 를 읽어서 작가에게 넘겨요
from 공통 import 주제_읽기, 주제폴더, 초안_쓰기, 제목과_본문, 글자수

주제 = 주제_읽기()[0]                       # 주제 1번
폴더 = 주제폴더(주제)
개요 = (폴더 / "1_개요.md").read_text(encoding="utf-8")   # 앞 단계 결과 받기
print(f"📋 주제 {주제['번호']}: {주제['주제']} (목표 분량: {주제['분량']})")
print("② 작가가 개요를 보고 초안을 쓰는 중... (20~60초)\n")

초안 = 초안_쓰기(주제, 개요)
print(초안)

제목, 본문 = 제목과_본문(초안)
print(f"\n📏 제목 {len(제목)}자 / 본문 {글자수(본문)}자 (띄어쓰기 포함, 목표 {주제['분량']})")

저장 = 폴더 / "2_초안.md"
저장.write_text(초안, encoding="utf-8")
print(f"💾 저장: {저장.relative_to(저장.parents[2])}")
