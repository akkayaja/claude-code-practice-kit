# 미션 5: 주제 5개를 한 번에 돌리고, 결과와 검수 기록을 저장하기
#  편집부 5팀이 '동시에' 주제 하나씩 맡아 일해요 (차례로 하면 4~5분 → 동시에 하면 1~2분)
#  결과: 결과/전체/주제1~5/ (단계별 파일) + 결과/전체/검수기록.csv + 결과/전체/요약.csv
import csv
import shutil
import time
from concurrent.futures import ThreadPoolExecutor   # 여러 일을 동시에 시키는 도구
from 공통 import 주제_읽기, 주제폴더, 결과폴더, 개요_쓰기, 초안_쓰기, 검수루프, 제목과_본문, 글자수

전체폴더 = 결과폴더 / "전체"
shutil.rmtree(전체폴더, ignore_errors=True)          # 다시 돌릴 때 지난번 결과 비우기


def 한팀_일하기(주제):
    """편집부 한 팀이 주제 하나를 처음부터 끝까지 처리한다."""
    번호 = 주제["번호"]
    말하기 = lambda 글: print(f"[주제{번호}] {글.strip()}", flush=True)   # 어느 팀 소식인지 앞에 붙이기
    시작 = time.time()
    폴더 = 주제폴더(주제, "전체")

    말하기("① 개요 짜는 중...")
    개요 = 개요_쓰기(주제)
    (폴더 / "1_개요.md").write_text(개요, encoding="utf-8")
    말하기("② 초안 쓰는 중...")
    초안 = 초안_쓰기(주제, 개요)
    (폴더 / "2_초안.md").write_text(초안, encoding="utf-8")
    완성본, 기록 = 검수루프(주제, 초안, 폴더, 말하기)

    제목, 본문 = 제목과_본문(완성본)
    초 = round(time.time() - 시작)
    말하기(f"🏁 끝 ({초}초)")
    return 주제, 제목, 글자수(본문), 기록, 초


print("📚 주제 5개를 편집부 5팀이 동시에 처리합니다... (1~2분)\n")
with ThreadPoolExecutor(max_workers=5) as 사무실:
    결과들 = list(사무실.map(한팀_일하기, 주제_읽기()))

# 검수 기록: 검수 한 번이 한 줄 (주제마다 1~3줄)
with open(전체폴더 / "검수기록.csv", "w", encoding="utf-8-sig", newline="") as f:
    쓰기 = csv.writer(f)
    쓰기.writerow(["번호", "주제", "회차", "결과", "불통과항목", "본문글자수"])
    for 주제, _, _, 기록, _ in 결과들:
        for b in 기록:
            쓰기.writerow([주제["번호"], 주제["주제"], b["회차"], "통과" if b["통과"] else "불통과",
                         " ".join(map(str, b["불통과항목"])), b["본문글자수"]])

# 요약: 주제 하나가 한 줄
print("\n" + "=" * 60)
print(f"{'번호':<3}{'최종':<6}{'검수':>4}{'수정':>4}{'분량':>11}{'시간':>6}  제목")
with open(전체폴더 / "요약.csv", "w", encoding="utf-8-sig", newline="") as f:
    쓰기 = csv.writer(f)
    쓰기.writerow(["번호", "제목", "목표분량", "최종본문글자수", "검수횟수", "수정횟수", "최종결과", "걸린초"])
    for 주제, 제목, 본문수, 기록, 초 in 결과들:
        수정 = len(기록) - 1
        최종 = "통과" if 기록[-1]["통과"] else "사람확인"
        쓰기.writerow([주제["번호"], 제목, 주제["분량"], 본문수, len(기록), 수정, 최종, 초])
        print(f"{주제['번호']:<4}{'✅' if 최종 == '통과' else '⛔'}{최종:<5}{len(기록):>4}{수정:>4}"
              f"{f'{본문수}/{주제['분량']}':>11}{초:>5}초  {제목}")

통과수 = sum(기록[-1]["통과"] for _, _, _, 기록, _ in 결과들)
print("=" * 60)
print(f"🎉 통과 {통과수}/5, 수정 총 {sum(len(r[3]) - 1 for r in 결과들)}번")
print("💾 저장: 결과/전체/주제1~5/, 결과/전체/검수기록.csv, 결과/전체/요약.csv")
