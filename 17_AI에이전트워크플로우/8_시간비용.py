# 도전 미션 1: 단계별 소요 시간·비용 기록하기
#  7번처럼 5팀이 동시에 일하고, Claude에게 일을 맡길 때마다 '몇 초, 토큰 몇 개'를 기록장에 적어요
#  결과: 결과/시간비용/단계별기록.csv (한 번 맡길 때마다 한 줄) + 화면에 단계별 합계표
import csv
import shutil
import time
from concurrent.futures import ThreadPoolExecutor
import 공통
from 공통 import 주제_읽기, 주제폴더, 결과폴더, 개요_쓰기, 초안_쓰기, 검수루프

# 💰 요금 기준 (Claude Opus 5.5 공식 가격표, 2026-11 기준)
입력단가 = 4 / 1_000_000     # 입력(보낸 글) 토큰 1개당 4달러/100만 개
출력단가 = 20 / 1_000_000    # 출력(받은 글 + AI가 속으로 생각한 것) 토큰 1개당 20달러/100만 개
환율 = 1400                  # 1달러 = 1,400원으로 계산 (대략값)

폴더 = 결과폴더 / "시간비용"
shutil.rmtree(폴더, ignore_errors=True)


def 비용(줄):
    """기록 한 줄의 요금(원)"""
    return (줄["입력토큰"] * 입력단가 + 줄["출력토큰"] * 출력단가) * 환율


def 한팀_일하기(주제):
    공통.지금주제.번호 = 주제["번호"]                 # 이 팀은 몇 번 주제 담당인지 기록장에 알려 주기
    팀폴더 = 주제폴더(주제, "시간비용")
    말하기 = lambda 글: print(f"[주제{주제['번호']}] {글.strip()}", flush=True)
    개요 = 개요_쓰기(주제)
    초안 = 초안_쓰기(주제, 개요)
    검수루프(주제, 초안, 팀폴더, 말하기)


print("⏱ 5팀이 동시에 일하면서 단계마다 시간·토큰을 기록합니다... (1~2분)\n")
시작 = time.time()
with ThreadPoolExecutor(max_workers=5) as 사무실:
    list(사무실.map(한팀_일하기, 주제_읽기()))
전체초 = round(time.time() - 시작)

# 📒 기록장 저장: Claude에게 한 번 맡길 때마다 한 줄
with open(폴더 / "단계별기록.csv", "w", encoding="utf-8-sig", newline="") as f:
    쓰기 = csv.writer(f)
    쓰기.writerow(["주제", "단계", "걸린초", "입력토큰", "출력토큰", "비용_원"])
    for 줄 in sorted(공통.사용기록, key=lambda 줄: (줄["주제"], 줄["단계"])):
        쓰기.writerow([줄["주제"], 줄["단계"], 줄["초"], 줄["입력토큰"], 줄["출력토큰"], round(비용(줄), 1)])

# 📊 단계별 합계표
print("\n" + "=" * 62)
print(f"{'단계':<6}{'횟수':>4}{'평균 시간':>10}{'입력토큰':>9}{'출력토큰':>9}{'비용':>10}")
for 단계 in ["①개요", "②초안", "③검수", "④수정"]:
    줄들 = [줄 for 줄 in 공통.사용기록 if 줄["단계"] == 단계]
    if not 줄들:
        print(f"{단계:<6}{0:>5}")
        continue
    평균초 = sum(줄["초"] for 줄 in 줄들) / len(줄들)
    print(f"{단계:<6}{len(줄들):>5}{평균초:>10.1f}초{sum(줄['입력토큰'] for 줄 in 줄들):>10,}"
          f"{sum(줄['출력토큰'] for 줄 in 줄들):>10,}{sum(비용(줄) for 줄 in 줄들):>10.0f}원")
합계 = sum(비용(줄) for 줄 in 공통.사용기록)
print("=" * 62)
print(f"🧾 Claude 호출 {len(공통.사용기록)}번, 전체 {전체초}초, 총 {합계:.0f}원 (글 1편당 약 {합계 / 5:.0f}원)")
print("💾 저장: 결과/시간비용/단계별기록.csv")
