# 미션 4: 검수에서 불통과면 수정 단계로 '되돌아가게' 만들기 (최대 2번)
#  사용법: 6_검수루프.py 주제번호   (예: 6_검수루프.py 3 → 주제 3번)
import sys
from 공통 import 주제_읽기, 주제폴더, 개요_쓰기, 초안_쓰기, 검수루프, 제목과_본문, 글자수

번호 = sys.argv[1] if len(sys.argv) > 1 else "1"     # 주제 번호를 안 주면 1번
주제 = next(t for t in 주제_읽기() if t["번호"] == 번호)
for 옛파일 in 주제폴더(주제, "루프").iterdir():   # 다시 돌릴 때 지난번 파일이 섞이지 않게 비우기
    옛파일.unlink()
폴더 = 주제폴더(주제, "루프")
print(f"📋 주제 {주제['번호']}: {주제['주제']} (목표 {주제['분량']})\n")

print("   ① 기획자: 개요 짜는 중...")
개요 = 개요_쓰기(주제)
(폴더 / "1_개요.md").write_text(개요, encoding="utf-8")
print("   ② 작가: 초안 쓰는 중...")
초안 = 초안_쓰기(주제, 개요)
(폴더 / "2_초안.md").write_text(초안, encoding="utf-8")

완성본, 기록 = 검수루프(주제, 초안, 폴더)            # ← 여기서 검수 ↔ 수정이 돌고 돌아요

수정횟수 = len([b for b in 기록 if not b["통과"] and b["회차"] <= 2])
print(f"\n🎉 끝! 검수 {len(기록)}번, 수정 {수정횟수}번 → 최종 {'✅ 통과' if 기록[-1]['통과'] else '⛔ 사람 확인 필요'}")
print(f"💾 결과 폴더: 결과/루프/주제{번호}/  ({len(list(폴더.iterdir()))}개 파일)")
