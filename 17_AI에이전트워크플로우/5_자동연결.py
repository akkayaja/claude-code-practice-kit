# 미션 3: 네 단계를 사람 손 없이 자동으로 이어 주기 (컨베이어 벨트)
#  미션 2에서 사람이 파일을 들고 다음 직원에게 가던 일을, 코드가 대신 건네줘요
#  결과는 수동 결과와 섞이지 않게 결과/자동/주제1/ 에 저장해요
import json
from 공통 import 주제_읽기, 주제폴더, 개요_쓰기, 초안_쓰기, 검수하기, 검수표, 수정하기, 제목과_본문, 글자수

주제 = 주제_읽기()[0]                       # 주제 1번
폴더 = 주제폴더(주제, "자동")
print(f"📋 주제 {주제['번호']}: {주제['주제']} (목표 {주제['분량']})\n")

print("① 기획자: 개요 짜는 중...")
개요 = 개요_쓰기(주제)
(폴더 / "1_개요.md").write_text(개요, encoding="utf-8")

print("② 작가: 초안 쓰는 중...")
초안 = 초안_쓰기(주제, 개요)                       # ← 개요를 '자동으로' 건네줌
(폴더 / "2_초안.md").write_text(초안, encoding="utf-8")
제목, 본문 = 제목과_본문(초안)
print(f"   제목: {제목} ({len(제목)}자) / 본문 {글자수(본문)}자")

print("③ 편집장: 검수하는 중...")
검수결과 = 검수하기(주제, 초안)                    # ← 초안을 '자동으로' 건네줌
(폴더 / "3_검수.md").write_text(검수표(검수결과), encoding="utf-8")
(폴더 / "3_검수.json").write_text(json.dumps(검수결과, ensure_ascii=False, indent=2), encoding="utf-8")
불통과 = [항목["번호"] for 항목 in 검수결과["항목"] if not 항목["통과"]]
print(f"   → {'✅ 통과' if 검수결과['통과'] else '❌ 불통과 ' + str(불통과)}")

if 검수결과["통과"]:
    print("④ 수정: 통과했으니 건너뛰기 → 초안이 곧 완성본")
    완성본 = 초안
else:
    print("④ 작가: 불통과 항목 고치는 중...")
    완성본 = 수정하기(주제, 초안, 검수결과)        # ← 원고 + 메모를 '자동으로' 건네줌
    (폴더 / "4_수정본.md").write_text(완성본, encoding="utf-8")
    제목, 본문 = 제목과_본문(완성본)
    print(f"   본문 {글자수(본문)}자")

print(f"\n🎉 한 바퀴 끝! 결과 폴더: 결과/자동/주제1/  ({len(list(폴더.iterdir()))}개 파일)")
