def 사장님_요청_반영(주제, 글, 요청):
    """④ 작가: 사장님이 반려하며 적은 요청대로 글을 고친다 (B안: 반려 → 다시 컨베이어 벨트로)."""
    지시문 = f"""너는 편집부 작가야. 발행 책임자(사장님)가 글을 반려하며 요청 사항을 남겼어.
요청을 최우선으로 반영해서 글 전체를 다시 출력해.
규칙
- 요청과 상관없는 부분은 되도록 그대로 둬.
- 첫 줄은 '# 제목' 한 줄, 그다음 줄부터 본문.
- 본문 분량은 띄어쓰기 포함 약 {주제['분량']} (±10% 안)을 지켜.
- 통계·퍼센트처럼 출처 없는 숫자는 쓰지 마.
- 고친 글만 출력하고 설명이나 인사말은 쓰지 마."""
    메시지 = f"[사장님 요청]\n{요청}\n\n[원래 글]\n{글}"
    return 클로드에게_묻기(메시지, 지시문, 단계="④수정(사장님)")
