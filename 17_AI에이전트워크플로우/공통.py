# ───────── 글자 세기 (숫자 세기는 AI 말고 코드가!) ─────────

def 제목과_본문(글):
    """글 맨 위 '# 제목' 줄을 제목으로, 나머지를 본문으로 나눈다."""
    줄들 = 글.strip().splitlines()
    if 줄들 and 줄들[0].startswith("#"):
        return 줄들[0].lstrip("#").strip(), "\n".join(줄들[1:]).strip()
    return "", 글.strip()


def 글자수(글):
    """본문 글자 수 = 줄바꿈과 꾸밈 기호(#, *)를 뺀 글자 수 (띄어쓰기는 포함)."""
    return len(re.sub(r"[#*\n]", "", 글))


def 목표분량(주제):
    return int(주제["분량"].replace("자", ""))


# ───────── Claude에게 일 맡기기 (16번과 같은 방식) ─────────

def 클로드에게_묻기(메시지, 지시문, 형식=None, 단계=""):
    """Claude에게 일 하나를 맡기고 대답 글자만 돌려준다.
    형식(JSON 설계도)을 주면 그 모양 그대로의 JSON 글자로 답하게 한다."""
    import anthropic                    # Claude와 대화하는 공식 도구
    from dotenv import load_dotenv      # .env 금고를 여는 도구
    load_dotenv(여기.parent / "03_메일분류" / ".env")   # 03번 금고에서 API 키를 빌려 온다
    시작 = time.time()                                  # ⏱ 스톱워치 시작
    출력설정 = {"effort": "low"}                        # "가볍게 생각해" (요금 절약)
    if 형식:
        출력설정["format"] = {"type": "json_schema", "schema": 형식}
    응답 = anthropic.Anthropic().beta.messages.create(
        model=모델,
        max_tokens=8000,
        system=지시문,
        messages=[{"role": "user", "content": 메시지}],
        output_config=출력설정,
        betas=["server-side-fallback-2026-07-01"],   # 혹시 AI가 거절하면
        fallbacks="default",                         #   다른 모델이 이어받게 하는 안전장치
    )
    사용기록.append({                                   # 📒 기록장에 한 줄 적기
        "주제": getattr(지금주제, "번호", ""), "단계": 단계,
        "초": round(time.time() - 시작, 1),
        "입력토큰": 응답.usage.input_tokens, "출력토큰": 응답.usage.output_tokens,
    })
    if 응답.stop_reason == "refusal":
        return "(거절)"
    글 = "".join(조각.text for 조각 in 응답.content if 조각.type == "text")
    if not 형식:
        글 = re.sub(r"</?[A-Za-z_]+>", "", 글)   # 가끔 섞이는 <final> 같은 꼬리표 지우기
    return 글.strip()


