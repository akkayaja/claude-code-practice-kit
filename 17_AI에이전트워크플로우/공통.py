# ───────── ③ 편집장: 검수하기 ─────────
#  사용자가 정한 기준(A안): 4번 '근거 없는 숫자'는 출처가 필요한 통계·사실 주장만 불통과,
#  예시 이야기 속 숫자나 글에서 직접 계산해 보인 숫자는 통과

검수형식 = {   # 편집장이 꼭 이 모양(JSON)으로 답하게 하는 설계도
    "type": "object",
    "properties": {
        "항목": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "번호": {"type": "integer"},
                    "이유": {"type": "string"},      # 이유를 '먼저' 쓰고
                    "통과": {"type": "boolean"},     #   그다음에 통과/불통과 도장 찍기
                    "수정제안": {"type": "string"},
                },
                "required": ["번호", "이유", "통과", "수정제안"],
                "additionalProperties": False,
            },
        },
        "총평": {"type": "string"},
    },
    "required": ["항목", "총평"],
    "additionalProperties": False,
}


def 검수하기(주제, 글):
    """③ 편집장: 검수기준 6개 항목을 채점한다.
    글자 수는 코드가 직접 세서 '사실'로 건네고, 5번(분량)은 코드가 최종 판정한다.
    돌려주는 것: {'항목': [...6개], '총평': ..., '통과': True/False, '제목글자수':.., '본문글자수':..}"""
    제목, 본문 = 제목과_본문(글)
    목표 = 목표분량(주제)
    아래, 위 = round(목표 * 0.85), round(목표 * 1.15)
    본문수 = 글자수(본문)

    지시문 = f"""너는 깐깐하지만 공정한 편집장이야. 아래 [검수 기준] 6개 항목을 하나씩 채점해.
- 항목마다 먼저 '이유'에 근거를 쓰고, 그 이유와 맞게 '통과'를 정해. 기준을 형식상 충족하면 아쉬운 점이 있어도 통과야.
- 통과 못 한 항목은 '수정제안'에 작가가 바로 고칠 수 있게 구체적으로 써. 통과면 수정제안은 빈 글자("")로.
- 4번 판단 기준: "~%가", "연구에 따르면", "평균 ~배"처럼 출처가 있어야 믿을 수 있는 통계·사실 주장만 불통과야.
  예시 이야기 속 숫자(예: 거래처 300곳)나 글 안에서 직접 계산해 보인 숫자(예: 30분×240일=120시간)는 통과야.
- 글자 수는 [측정값]을 그대로 믿어. 직접 세지 마.

[검수 기준]
{검수기준_읽기()}"""
    메시지 = f"""주제: {주제['주제']} / 독자: {주제['독자']} / 지정 분량: {주제['분량']}
[측정값] 제목 {len(제목)}자, 본문 {본문수}자 (띄어쓰기 포함). 분량 통과 범위: {아래}~{위}자

[검수할 글]
{글}"""
    결과 = json.loads(클로드에게_묻기(메시지, 지시문, 형식=검수형식, 단계="③검수"))

    # 5번(분량)은 숫자 비교라 코드가 최종 판정 (계산은 계산기에게!)
    for 항목 in 결과["항목"]:
        if 항목["번호"] == 5:
            항목["통과"] = 아래 <= 본문수 <= 위
            항목["이유"] = f"본문 {본문수}자 (통과 범위 {아래}~{위}자)"
            if 항목["통과"]:
                항목["수정제안"] = ""
            elif 본문수 < 아래:
                항목["수정제안"] = f"본문을 약 {목표 - 본문수}자 늘려 {목표}자 가까이 맞춰 주세요."
            else:
                항목["수정제안"] = f"본문을 약 {본문수 - 목표}자 줄여 {목표}자 가까이 맞춰 주세요."
    결과["통과"] = all(항목["통과"] for 항목 in 결과["항목"])
    결과["제목글자수"], 결과["본문글자수"] = len(제목), 본문수
    return 결과


def 검수표(결과):
    """검수 결과를 사람이 읽기 좋은 글(마크다운 표)로 바꾼다."""
    줄 = ["| 번호 | 결과 | 이유 | 수정 제안 |", "|---|---|---|---|"]
    for 항목 in 결과["항목"]:
        표시 = "✅ 통과" if 항목["통과"] else "❌ 불통과"
        줄.append(f"| {항목['번호']} | {표시} | {항목['이유']} | {항목['수정제안'] or '-'} |")
    최종 = "✅ 통과" if 결과["통과"] else "❌ 불통과"
    불통과수 = sum(not 항목["통과"] for 항목 in 결과["항목"])
    줄 += ["", f"**최종: {최종}** (불통과 {불통과수}개) / 총평: {결과['총평']}"]
    return "\n".join(줄)


# ───────── ④ 작가: 검수 메모대로 고쳐 쓰기 ─────────

def 수정하기(주제, 글, 검수결과, 꼭지킬것=""):
    """④ 작가: 편집장의 불통과 항목·수정 제안만 반영해 글을 고친다 (통과한 부분은 그대로 살리기)."""
    고칠것 = "\n".join(
        f"- {항목['번호']}번: {항목['이유']}\n  → 수정 제안: {항목['수정제안']}"
        for 항목 in 검수결과["항목"] if not 항목["통과"]
    )
    지시문 = f"""너는 편집부 작가야. 편집장이 불통과를 준 항목만 고쳐서 글 전체를 다시 출력해.
규칙
- 통과한 부분(예시, 계산, 마지막 행동 제안 등)은 되도록 그대로 둬.
- 첫 줄은 '# 제목' 한 줄, 그다음 줄부터 본문.
- 본문 분량은 띄어쓰기 포함 약 {주제['분량']} (±10% 안)을 지켜.
- 통계·퍼센트처럼 출처 없는 숫자는 쓰지 마.
- 고친 글만 출력하고 설명이나 인사말은 쓰지 마."""
    if 꼭지킬것:   # 사장님이 반려하며 요청한 것은 편집장 메모를 따를 때도 지우지 말기
        지시문 += f"\n- [사장님 요청]은 이미 반영돼 있어. 편집장 메모를 따르더라도 사장님 요청은 꼭 살려 둬: {꼭지킬것}"
    메시지 = f"[편집장이 고치라고 한 것]\n{고칠것}\n\n[원래 글]\n{글}"
    return 클로드에게_묻기(메시지, 지시문, 단계="④수정")


# ───────── 미션 4: 검수 → 수정 되돌이 고리 (최대 2번) ─────────

최대수정 = 2   # 무한 반복을 막는 안전장치: 고쳐 쓰기는 최대 2번까지만


def 검수루프(주제, 초안, 폴더, 말하기=print, 꼭지킬것=""):
    """검수 → (불통과면) 수정 → 다시 검수 … 를 통과하거나 수정 2번을 다 쓸 때까지 반복한다.
    회차마다 검수표·수정본을 파일로 남기고, 돌려주는 것: (완성본, 회차별 기록 목록)"""
    글 = 초안
    기록 = []
    for 회차 in range(1, 최대수정 + 2):          # 검수는 최대 3번 (처음 1번 + 수정 후 2번)
        검수결과 = 검수하기(주제, 글)
        불통과 = [항목["번호"] for 항목 in 검수결과["항목"] if not 항목["통과"]]
        (폴더 / f"3_검수_{회차}차.md").write_text(검수표(검수결과), encoding="utf-8")
        기록.append({"회차": 회차, "통과": 검수결과["통과"], "불통과항목": 불통과,
                     "본문글자수": 검수결과["본문글자수"]})
        말하기(f"   ③ {회차}차 검수: {'✅ 통과' if 검수결과['통과'] else '❌ 불통과 ' + str(불통과)}"
               f" (본문 {검수결과['본문글자수']}자)")
        if 검수결과["통과"]:
            break                                     # 통과 → 고리에서 빠져나오기
        if 회차 > 최대수정:
            말하기(f"   ⛔ 수정 {최대수정}번을 다 썼어요 → 사람이 직접 확인 필요")
            break                                     # 안전장치 → 더 돌지 않기
        말하기(f"   ④ {회차}차 수정: 불통과 {불통과}번 고치는 중...")
        글 = 수정하기(주제, 글, 검수결과, 꼭지킬것)
        (폴더 / f"4_수정본_{회차}차.md").write_text(글, encoding="utf-8")
    (폴더 / "5_완성본.md").write_text(글, encoding="utf-8")
    return 글, 기록


