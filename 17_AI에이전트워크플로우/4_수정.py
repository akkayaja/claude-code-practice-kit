# 미션 2-④: 편집장의 메모(3_검수.json)를 작가에게 돌려보내 '수정'시키기 (수동 4단계)
import json
from 공통 import 주제_읽기, 주제폴더, 수정하기, 제목과_본문, 글자수

주제 = 주제_읽기()[0]                       # 주제 1번
폴더 = 주제폴더(주제)
초안 = (폴더 / "2_초안.md").read_text(encoding="utf-8")                       # 작가가 쓴 원고
검수결과 = json.loads((폴더 / "3_검수.json").read_text(encoding="utf-8"))      # 편집장의 빨간 펜 메모

if 검수결과["통과"]:
    print("✅ 검수를 이미 통과했어요. 고칠 게 없어요!")
    raise SystemExit

불통과 = [str(항목["번호"]) for 항목 in 검수결과["항목"] if not 항목["통과"]]
print(f"📋 주제 {주제['번호']}: {주제['주제']}")
print(f"④ 작가가 불통과 항목({', '.join(불통과)}번)을 고치는 중... (20~60초)\n")

수정본 = 수정하기(주제, 초안, 검수결과)
print(수정본)

제목, 본문 = 제목과_본문(수정본)
print(f"\n📏 제목 {len(제목)}자 / 본문 {글자수(본문)}자 (띄어쓰기 포함, 목표 {주제['분량']})")
(폴더 / "4_수정본.md").write_text(수정본, encoding="utf-8")
print("💾 저장: 결과/주제1/4_수정본.md")
