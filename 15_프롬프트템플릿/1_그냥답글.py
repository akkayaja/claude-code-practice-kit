# 기본 미션 1: 아무 규칙 없이 "답글 써 줘"라고만 했을 때 AI가 어떻게 쓰는지 본다
# 실행 (15 폴더에서): ../03_메일분류/.venv/bin/python 1_그냥답글.py

from 공통 import 리뷰_읽기, 클로드에게_묻기

비교할_리뷰번호 = ["4", "8", "9"]   # 화난 리뷰 / 애매한 리뷰 / 별점은 5인데 불만인 리뷰

for 리뷰 in 리뷰_읽기():
    if 리뷰["리뷰번호"] not in 비교할_리뷰번호:
        continue
    답글 = 클로드에게_묻기(f"답글 써 줘\n\n{리뷰['리뷰내용']}")   # 규칙 없이 딱 이것만!
    print("=" * 60)
    print(f"[리뷰 {리뷰['리뷰번호']}] 별점 {리뷰['별점']} — {리뷰['리뷰내용']}")
    print("-" * 60)
    print(답글)
    print(f"\n(글자 수: {len(답글)}자)")
print("=" * 60)
