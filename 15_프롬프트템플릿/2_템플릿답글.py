# 기본 미션 3: 미션 1과 같은 리뷰 3개를, 이번엔 템플릿(업무 매뉴얼)을 주고 다시 시켜 본다
# 실행 (15 폴더에서): ../03_메일분류/.venv/bin/python 2_템플릿답글.py

from pathlib import Path

from 공통 import 리뷰_읽기, 클로드에게_묻기

템플릿파일 = "템플릿_v1.txt"                 # ✏️ 어떤 매뉴얼을 줄지 — 여기만 바꾸면 돼요
템플릿 = Path(템플릿파일).read_text(encoding="utf-8")

비교할_리뷰번호 = ["4", "8", "9"]            # 미션 1과 똑같은 리뷰

print(f"사용한 템플릿: {템플릿파일}")
for 리뷰 in 리뷰_읽기():
    if 리뷰["리뷰번호"] not in 비교할_리뷰번호:
        continue
    질문 = f"별점: {리뷰['별점']}점\n리뷰: {리뷰['리뷰내용']}"
    결과 = 클로드에게_묻기(질문, 지시문=템플릿)        # 템플릿을 '지시문'으로 함께 보낸다

    답글줄 = next((줄 for 줄 in 결과.splitlines() if 줄.startswith("답글:")), "")
    답글 = 답글줄.removeprefix("답글:").strip()

    print("=" * 60)
    print(f"[리뷰 {리뷰['리뷰번호']}] 별점 {리뷰['별점']} — {리뷰['리뷰내용']}")
    print("-" * 60)
    print(결과)
    print(f"\n(답글 글자 수: {len(답글)}자)")
print("=" * 60)
