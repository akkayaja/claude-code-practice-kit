# 도전 미션 B: 고객문의 칸의 메일마다 답장 초안을 자동으로 써서 답장초안/ 폴더에 저장한다.
# (먼저 python3 메일분류.py 를 실행해서 분류결과/고객문의/ 폴더가 있어야 해요)

import re
import shutil
from email import policy
from email.parser import BytesParser
from pathlib import Path

# ============================================================
# ✏️ 답장 규칙 — 여기만 고치면 돼요!
#   (찾을 단어, 문의 종류, 답장에 넣을 안내문)
#   위에서부터 검사해서 처음 맞는 안내문을 써요.
# ============================================================
답장규칙 = [
    ("환불", "환불", "환불은 [마이페이지 > 주문내역]에서 '환불 신청'을 누르시면 접수됩니다.\n"
                    "제품 회수 후 영업일 기준 3~5일 안에 결제하신 수단으로 환불됩니다."),
    ("교환", "교환", "교환은 제품 수령 후 7일 이내에 가능합니다.\n"
                    "[마이페이지 > 주문내역]에서 '교환 신청'을 누르시면 회수 기사님이 방문합니다."),
    ("배송", "배송", "배송이 늦어져 불편을 드려 죄송합니다.\n"
                    "택배사에 확인 후 오늘 안에 현재 배송 위치를 다시 안내드리겠습니다."),
    ("탈퇴", "회원탈퇴", "회원 탈퇴는 [마이페이지 > 회원정보 > 회원 탈퇴]에서 바로 하실 수 있습니다.\n"
                       "탈퇴하시면 적립금과 주문 기록이 모두 삭제되니 참고 부탁드립니다."),
    ("사용법", "사용법", "제품 사용 설명서(PDF)를 첨부해 드리니 확인 부탁드립니다.\n"
                       "그래도 어려우시면 고객센터(1588-0000)로 연락 주시면 자세히 안내드리겠습니다."),
]
기본안내문 = "문의 주신 내용을 담당자가 확인한 뒤 1영업일 안에 다시 연락드리겠습니다."
보내는사람 = "고객지원팀"
# ============================================================

고객문의폴더 = Path("분류결과") / "고객문의"
답장폴더 = Path("답장초안")

# 주문번호 모양: "A-" 뒤에 숫자가 이어지는 것 (예: A-20261102)
주문번호모양 = re.compile(r"[A-Z]-\d+")

if 답장폴더.exists():
    shutil.rmtree(답장폴더)
답장폴더.mkdir()

for 메일파일 in sorted(고객문의폴더.glob("*.eml")):
    with open(메일파일, "rb") as f:
        메일 = BytesParser(policy=policy.default).parse(f)

    이름 = 메일["From"].addresses[0].display_name
    제목 = 메일["Subject"]
    본문 = 메일.get_body(preferencelist=("plain",)).get_content()
    검사할글 = 제목 + "\n" + 본문

    # 1) 어떤 종류의 문의인지 찾고, 맞는 안내문 고르기
    종류, 안내문 = "기타", 기본안내문
    for 단어, 규칙종류, 규칙안내문 in 답장규칙:
        if 단어 in 검사할글:
            종류, 안내문 = 규칙종류, 규칙안내문
            break                                # 처음 맞는 규칙에서 멈춤

    # 2) 주문번호가 있으면 답장에 같이 적어 주기
    찾음 = 주문번호모양.search(본문)
    주문번호줄 = f"(확인한 주문번호: {찾음.group()})\n\n" if 찾음 else ""

    # 3) 답장 초안 만들기 — f"...{이름}..." 처럼 { } 안에 값이 채워져요
    답장 = (
        f"받는 사람: {메일['From']}\n"
        f"제목: RE: {제목}\n"
        f"\n"
        f"{이름}님, 안녕하세요. {보내는사람}입니다.\n"
        f"문의 주셔서 감사합니다.\n"
        f"\n"
        f"{주문번호줄}"
        f"{안내문}\n"
        f"\n"
        f"감사합니다.\n"
        f"{보내는사람} 드림\n"
    )

    저장위치 = 답장폴더 / f"{메일파일.stem}_답장.txt"
    저장위치.write_text(답장, encoding="utf-8")
    print(f"{메일파일.name}  [{종류}]  {이름}님 → {저장위치}")

print("-" * 60)
print(f"답장 초안 {len(list(답장폴더.glob('*.txt')))}개를 {답장폴더}/ 폴더에 저장했어요.")
print("⚠️ 초안이에요! 보내기 전에 꼭 사람이 읽고 고쳐 주세요.")
