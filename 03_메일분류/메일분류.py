# 미션 4: 내가 정한 규칙대로 메일을 분류결과/카테고리명/ 폴더로 복사한다.

import shutil                               # 파일 복사·폴더 지우기 도구
from email import policy
from email.parser import BytesParser
from pathlib import Path

# ============================================================
# ✏️ 분류 규칙 — 여기만 고치면 돼요!
#   - 위에서부터 순서대로 검사해서, 처음 맞는 칸에 넣어요.
#   - 단어를 추가하려면 따옴표 안에 쓰고 쉼표(,)로 구분해요.
# ============================================================
분류규칙 = [
    ("스팸",     ["광고", "무료", "당첨"]),
    ("견적요청", ["견적", "가격"]),
    ("청구서",   ["청구", "대금", "세금계산서"]),
    ("사내공지", ["공지", "안내"]),
    ("고객문의", ["문의", "궁금"]),
]
기본칸 = "고객문의"        # 어떤 규칙에도 안 맞으면 들어갈 칸
본문도검사 = True          # True = 제목+본문에서 찾기 / False = 제목에서만 찾기
# ============================================================

INBOX = Path("inbox")
결과폴더 = Path("분류결과")


def 분류하기(검사할글):
    """검사할 글에서 규칙 단어를 순서대로 찾아, (칸 이름, 걸린 단어)를 돌려준다."""
    for 칸, 단어들 in 분류규칙:
        for 단어 in 단어들:
            if 단어 in 검사할글:
                return 칸, 단어
    return 기본칸, "(규칙 없음 → 기본칸)"


# 규칙을 고치고 다시 돌릴 때 예전 결과가 남지 않도록, 분류결과 폴더를 비우고 시작
if 결과폴더.exists():
    shutil.rmtree(결과폴더)

칸별개수 = {}

print(f"{'파일':<12} {'칸':<8} {'걸린 단어':<12} 제목")
print("-" * 80)

for 메일파일 in sorted(INBOX.glob("*.eml")):
    with open(메일파일, "rb") as f:
        메일 = BytesParser(policy=policy.default).parse(f)

    제목 = 메일["Subject"]
    본문 = 메일.get_body(preferencelist=("plain",)).get_content()   # 편지지 내용
    검사할글 = 제목 + "\n" + 본문 if 본문도검사 else 제목

    칸, 걸린단어 = 분류하기(검사할글)

    # 분류결과/칸이름/ 폴더를 만들고(이미 있으면 그대로) 메일을 복사
    칸폴더 = 결과폴더 / 칸
    칸폴더.mkdir(parents=True, exist_ok=True)
    shutil.copy2(메일파일, 칸폴더 / 메일파일.name)

    칸별개수[칸] = 칸별개수.get(칸, 0) + 1
    print(f"{메일파일.name:<12} {칸:<8} {걸린단어:<12} {제목}")

print("-" * 80)
for 칸, _ in 분류규칙:
    print(f"{칸}: {칸별개수.get(칸, 0)}통")
print(f"합계: {sum(칸별개수.values())}통 → {결과폴더}/ 폴더에 복사했어요.")
